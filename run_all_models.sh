#!/usr/bin/env bash
# Run HarmBench's DirectRequest text lane (240 behaviors, k=1) against the four target models.
#
# Scored by the canonical cais/HarmBench-Llama-2-13b-cls, served from Modal FDR by
# resources_servers/harmbench/classifier/modal_serve.py. The classifier is pinned to the
# revision the benchmark's provenance records, and its chat endpoint is verified to tokenize
# a prompt identically to upstream's raw vLLM call before any model is collected — a
# classifier fed a differently-tokenized prompt is a different classifier.
#
# Usage:  bash run_all_models.sh [model_key ...]
set -uo pipefail

ROOT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT_DIR"

RESULTS_DIR="${RESULTS_DIR:-results/harmbench}"
LOG_DIR="${LOG_DIR:-${RESULTS_DIR}/logs}"
mkdir -p "$RESULTS_DIR" "$LOG_DIR"

set -a; source "${ENV_FILE:-/Users/kruge/Documents/ChatGPT/NVIDIA/.env}"; set +a

: "${HARMBENCH_CLASSIFIER_BASE_URL:?set HARMBENCH_CLASSIFIER_BASE_URL}"
: "${HARMBENCH_CLASSIFIER_API_KEY:?set HARMBENCH_CLASSIFIER_API_KEY}"
export HARMBENCH_CLASSIFIER_CONCURRENCY="${HARMBENCH_CLASSIFIER_CONCURRENCY:-32}"

# prepare.py writes the paper's max_output_tokens: 512 into every row, and a per-row value
# beats anything set on the model server -- setting it under `policy_model` silently does
# nothing. These endpoints count reasoning tokens against that cap, so a reasoning model
# spends the whole budget thinking and returns empty text: at 512, Qwen3.5 came back empty on
# 193 of 240 behaviors and truncated on 227, and the classifier scored those blanks "No" for
# a meaningless 0.0% ASR across all four models.
#
# The cap is therefore raised on the target only, with `--max-output-tokens`, which is the
# override the benchmark's METRICS.md documents for exactly this reason. The paper's 512 still
# applies where it belongs: `generation_clip_tokens: 512` clips what the classifier reads, so
# the classified text is what the paper protocol would have seen.
TARGET_MAX_OUTPUT_TOKENS="${TARGET_MAX_OUTPUT_TOKENS:-8192}"

# Other Gym campaigns share this Mac; pin a head-server port and never pattern-kill app.py.
GYM_HEAD_SERVER_PORT="${GYM_HEAD_SERVER_PORT:-11784}"

stop_my_servers() {
    local pid cwd
    for pid in $(pgrep -f "python app.py" 2>/dev/null); do
        cwd="$(lsof -a -p "$pid" -d cwd -Fn 2>/dev/null | tail -1)"
        case "$cwd" in
            "n${ROOT_DIR}/"*) kill -9 "$pid" 2>/dev/null ;;
        esac
    done
    pkill -9 -f "gym eval run.*${RESULTS_DIR}" 2>/dev/null
    sleep 5
}

EXPECTED_ROWS=240

# key | slug | base_url | model id | token env var | concurrency
MODELS=(
"ultra|nemotron-3-ultra-550b|https://snorkelai-fdr--ep-nvidia-nemotron-3-ultra-550b-a55b-nvfp-63eebc.us-west.modal.direct/v1|nvidia/NVIDIA-Nemotron-3-Ultra-550B-A55B-NVFP4|MODAL_PROXY_TOKEN|48"
"qwen|qwen3.5-122b-a10b|https://snorkelai-fdr--ep-qwen3-5-122b-a10b-fp8-server.us-west.modal.direct/v1|Qwen/Qwen3.5-122B-A10B-FP8|MODAL_PROXY_TOKEN|32"
"kimi|kimi-k3|https://snorkelai-fdr--ep-kimi-k3-server.us-west.modal.direct/v1|moonshotai/Kimi-K3|MODAL_PROXY_TOKEN|24"
"supervl|nemotron-3.5-super-vl|https://snorkelai-fdr--nemotron-3-5-super-vl-ea-nemotronvision.us-east.modal.direct/v1|nvidia/NVIDIA-Nemotron-3.5-Super-VL-120B-A12B-BF16|SUPER_VL_MODAL_TOKEN|16"
)

write_env_yaml() {
    local base_url="$1" model="$2" token_var="$3"
    cat > env.yaml <<YAML
# Generated by run_all_models.sh — do not edit by hand.
head_server:
  host: 127.0.0.1
  port: ${GYM_HEAD_SERVER_PORT}

policy_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: ${base_url}
      api_key: \${oc.env:${token_var},""}
      model: ${model}
      uses_reasoning_parser: true
      num_concurrent_requests: 64
YAML
}

run_model() {
    local slug="$1" concurrency="$2"
    local out="${RESULTS_DIR}/${slug}.jsonl"
    local attempt status rows

    for attempt in 1 2 3; do
        echo "  [$(date +%H:%M:%S)] ${slug} attempt ${attempt} (concurrency ${concurrency}) -> ${out}"
        .venv/bin/gym eval run --resume \
            --benchmark harmbench \
            --agent harmbench_direct_request \
            --split benchmark \
            --output "$out" \
            --concurrency "$concurrency" \
            --max-output-tokens "$TARGET_MAX_OUTPUT_TOKENS" \
            > "${LOG_DIR}/${slug}.attempt${attempt}.log" 2>&1
        status=$?
        rows=$(wc -l < "$out" 2>/dev/null || echo 0)
        echo "  [$(date +%H:%M:%S)] ${slug} attempt ${attempt} exit=${status} rows=${rows}/${EXPECTED_ROWS}"

        if [ "$status" -eq 0 ] && [ "$rows" -ge "$EXPECTED_ROWS" ]; then
            echo "  [$(date +%H:%M:%S)] ${slug} complete"
            return 0
        fi

        concurrency=$(( concurrency / 2 ))
        [ "$concurrency" -lt 4 ] && concurrency=4
        echo "  [$(date +%H:%M:%S)] ${slug} backing off to concurrency ${concurrency}"
        stop_my_servers
        sleep 60
    done

    echo "  [$(date +%H:%M:%S)] ${slug} INCOMPLETE after 3 attempts (${rows}/${EXPECTED_ROWS})"
    return 1
}

WANTED=("$@")
for entry in "${MODELS[@]}"; do
    IFS='|' read -r key slug base_url model token_var model_concurrency <<< "$entry"
    if [ ${#WANTED[@]} -gt 0 ] && [[ ! " ${WANTED[*]} " =~ " ${key} " ]]; then
        continue
    fi

    echo "==============================================================="
    echo "[$(date +%H:%M:%S)] MODEL ${key} (${model})  classifier=cais/HarmBench-Llama-2-13b-cls"
    echo "==============================================================="

    write_env_yaml "$base_url" "$model" "$token_var"
    stop_my_servers
    run_model "$slug" "${CONCURRENCY_OVERRIDE:-$model_concurrency}"
done

stop_my_servers
echo "[$(date +%H:%M:%S)] All requested HarmBench models finished."
