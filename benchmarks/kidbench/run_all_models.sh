# Run the full KIDBench grid against each model in MODELS, one model at a time.
#
# Each model gets its own server stack because the endpoints differ in base URL and, for
# the early-access deployment, in credential. Both tracks run per model: the 5,000-row
# single-turn condition grid and the 200 five-turn child-actor conversations.
#
# Every stage passes --resume, so re-running after an interruption picks up where it
# stopped rather than re-spending GPU time on rollouts that already landed.
#
# Usage:  bash benchmarks/kidbench/run_all_models.sh [model_key ...]
set -uo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT_DIR"

RESULTS_DIR="${RESULTS_DIR:-results/kidbench}"
LOG_DIR="${LOG_DIR:-${RESULTS_DIR}/logs}"
SINGLE_CONCURRENCY="${SINGLE_CONCURRENCY:-96}"
MULTI_CONCURRENCY="${MULTI_CONCURRENCY:-48}"
mkdir -p "$RESULTS_DIR" "$LOG_DIR"

set -a; source "${ENV_FILE:-/Users/kruge/Documents/ChatGPT/NVIDIA/.env}"; set +a

# key | slug | base_url | model id | which token env var
MODELS=(
"ultra|nemotron-3-ultra-550b|https://snorkelai-fdr--ep-nvidia-nemotron-3-ultra-550b-a55b-nvfp-63eebc.us-west.modal.direct/v1|nvidia/NVIDIA-Nemotron-3-Ultra-550B-A55B-NVFP4|MODAL_PROXY_TOKEN"
"kimi|kimi-k3|https://snorkelai-fdr--ep-kimi-k3-server.us-west.modal.direct/v1|moonshotai/Kimi-K3|MODAL_PROXY_TOKEN"
"qwen|qwen3.5-122b-a10b|https://snorkelai-fdr--ep-qwen3-5-122b-a10b-fp8-server.us-west.modal.direct/v1|Qwen/Qwen3.5-122B-A10B-FP8|MODAL_PROXY_TOKEN"
"supervl|nemotron-3.5-super-vl|https://snorkelai-fdr--nemotron-3-5-super-vl-ea-nemotronvision.us-east.modal.direct/v1|nvidia/NVIDIA-Nemotron-3.5-Super-VL-120B-A12B-BF16|SUPER_VL_MODAL_TOKEN"
)

write_env_yaml() {
    local base_url="$1" model="$2" token_var="$3"
    cat > env.yaml <<YAML
# Generated by benchmarks/kidbench/run_all_models.sh — do not edit by hand.
policy_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: ${base_url}
      api_key: \${oc.env:${token_var},""}
      model: ${model}
      uses_reasoning_parser: true
      num_concurrent_requests: 64

kidbench_judge_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: https://openrouter.ai/api/v1
      api_key: \${oc.env:OPENROUTER_API_KEY_SNORKEL,""}
      model: deepseek/deepseek-v4-pro
      uses_reasoning_parser: false
      num_concurrent_requests: 64
      extra_body:
        reasoning:
          enabled: false

# Upstream scores multi-turn with the cheaper flash model; see
# scripts/evaluation/multi_turn/deepseek.sh at the pinned revision.
kidbench_multi_turn_judge_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: https://openrouter.ai/api/v1
      api_key: \${oc.env:OPENROUTER_API_KEY_SNORKEL,""}
      model: deepseek/deepseek-v4-flash
      uses_reasoning_parser: false
      num_concurrent_requests: 64
      extra_body:
        reasoning:
          enabled: false

kidbench_actor_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: https://snorkelai-fdr--ep-gemma-4-31b-it-server.us-west.modal.direct/v1
      api_key: \${oc.env:MODAL_PROXY_TOKEN,""}
      model: google/gemma-4-31B-it
      uses_reasoning_parser: false
      num_concurrent_requests: 64
YAML
}

stop_servers() {
    pkill -9 -f "gym env start" >/dev/null 2>&1
    pkill -9 -f "resources_servers/kidbench/app.py" >/dev/null 2>&1
    pkill -9 -f "responses_api_agents/.*app.py" >/dev/null 2>&1
    pkill -9 -f "responses_api_models/.*app.py" >/dev/null 2>&1
    sleep 5
}

start_servers() {
    local slug="$1"
    nohup .venv/bin/gym env start --config resources_servers/kidbench/configs/kidbench.yaml \
        > "${LOG_DIR}/${slug}.servers.log" 2>&1 &
    for _ in $(seq 1 60); do
        sleep 5
        if [ "$(.venv/bin/gym env status 2>/dev/null | grep -c '✓')" -ge 7 ]; then
            echo "  servers up"
            return 0
        fi
    done
    echo "  ERROR: servers did not come up for ${slug}" >&2
    return 1
}

run_track() {
    local slug="$1" agent="$2" input="$3" track="$4" concurrency="$5"
    local out="${RESULTS_DIR}/${slug}.${track}.jsonl"
    echo "  [$(date +%H:%M:%S)] ${slug} / ${track} -> ${out}"
    .venv/bin/gym eval run --no-serve --resume \
        --agent "$agent" \
        --input "$input" \
        --output "$out" \
        --num-repeats 1 \
        --concurrency "$concurrency" \
        > "${LOG_DIR}/${slug}.${track}.log" 2>&1
    local status=$?
    echo "  [$(date +%H:%M:%S)] ${slug} / ${track} exit=${status} rows=$(wc -l < "$out" 2>/dev/null || echo 0)"
    return $status
}

WANTED=("$@")
for entry in "${MODELS[@]}"; do
    IFS='|' read -r key slug base_url model token_var <<< "$entry"
    if [ ${#WANTED[@]} -gt 0 ] && [[ ! " ${WANTED[*]} " =~ " ${key} " ]]; then
        continue
    fi

    echo "==============================================================="
    echo "[$(date +%H:%M:%S)] MODEL ${key} (${model})"
    echo "==============================================================="

    write_env_yaml "$base_url" "$model" "$token_var"
    stop_servers
    start_servers "$slug" || continue

    run_track "$slug" kidbench_simple_agent \
        resources_servers/kidbench/data/single_turn.jsonl single_turn "$SINGLE_CONCURRENCY"
    run_track "$slug" kidbench_multi_turn_agent \
        resources_servers/kidbench/data/multi_turn.jsonl multi_turn "$MULTI_CONCURRENCY"
done

stop_servers
echo "[$(date +%H:%M:%S)] All requested models finished."
