#!/usr/bin/env bash
# Run InjecAgent's base setting (1,054 cases, k=1) against the four target models.
#
# There is no judge: attacker tool responses are the stored upstream simulations and the
# scorer is upstream's own, vendored. So a run is 1,054 rollouts of at most two model calls
# each and nothing else.
#
# All four models are collected here, including Kimi K3 which already has a reportable
# line, so the four-model table rests on one harness revision and one denominator.
#
# Usage:  bash run_all_models.sh [model_key ...]
set -uo pipefail

ROOT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT_DIR"

RESULTS_DIR="${RESULTS_DIR:-results/injecagent}"
LOG_DIR="${LOG_DIR:-${RESULTS_DIR}/logs}"
mkdir -p "$RESULTS_DIR" "$LOG_DIR"

set -a; source "${ENV_FILE:-/Users/kruge/Documents/ChatGPT/NVIDIA/.env}"; set +a

# Other Gym campaigns share this Mac. Pin a head-server port away from the 11000 default,
# and never pattern-kill `python app.py` — that is another worktree's campaign too.
GYM_HEAD_SERVER_PORT="${GYM_HEAD_SERVER_PORT:-11773}"

stop_my_servers() {
    local pid cwd
    for pid in $(pgrep -f "python app.py" 2>/dev/null); do
        cwd="$(lsof -a -p "$pid" -d cwd -Fn 2>/dev/null | tail -1)"
        case "$cwd" in
            "n${ROOT_DIR}/"*) kill -9 "$pid" 2>/dev/null ;;
        esac
    done
    pkill -9 -f "gym eval run.*${RESULTS_DIR}" 2>/dev/null
    sleep 5
}

EXPECTED_ROWS=1054

# key | slug | base_url | model id | token env var | concurrency
MODELS=(
"ultra|nemotron-3-ultra-550b|https://snorkelai-fdr--ep-nvidia-nemotron-3-ultra-550b-a55b-nvfp-63eebc.us-west.modal.direct/v1|nvidia/NVIDIA-Nemotron-3-Ultra-550B-A55B-NVFP4|MODAL_PROXY_TOKEN|64"
"qwen|qwen3.5-122b-a10b|https://snorkelai-fdr--ep-qwen3-5-122b-a10b-fp8-server.us-west.modal.direct/v1|Qwen/Qwen3.5-122B-A10B-FP8|MODAL_PROXY_TOKEN|32"
"kimi|kimi-k3|https://snorkelai-fdr--ep-kimi-k3-server.us-west.modal.direct/v1|moonshotai/Kimi-K3|MODAL_PROXY_TOKEN|24"
"supervl|nemotron-3.5-super-vl|https://snorkelai-fdr--nemotron-3-5-super-vl-ea-nemotronvision.us-east.modal.direct/v1|nvidia/NVIDIA-Nemotron-3.5-Super-VL-120B-A12B-BF16|SUPER_VL_MODAL_TOKEN|16"
)

write_env_yaml() {
    local base_url="$1" model="$2" token_var="$3"
    cat > env.yaml <<YAML
# Generated by run_all_models.sh — do not edit by hand.
head_server:
  host: 127.0.0.1
  port: ${GYM_HEAD_SERVER_PORT}

policy_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: ${base_url}
      api_key: \${oc.env:${token_var},""}
      model: ${model}
      uses_reasoning_parser: true
      num_concurrent_requests: 64
YAML
}

run_model() {
    local slug="$1" concurrency="$2"
    local out="${RESULTS_DIR}/${slug}.jsonl"
    local attempt status rows

    for attempt in 1 2 3; do
        echo "  [$(date +%H:%M:%S)] ${slug} attempt ${attempt} (concurrency ${concurrency}) -> ${out}"
        .venv/bin/gym eval run --resume \
            --benchmark injecagent \
            --agent injecagent_benchmark \
            --split benchmark \
            --output "$out" \
            --concurrency "$concurrency" \
            > "${LOG_DIR}/${slug}.attempt${attempt}.log" 2>&1
        status=$?
        rows=$(wc -l < "$out" 2>/dev/null || echo 0)
        echo "  [$(date +%H:%M:%S)] ${slug} attempt ${attempt} exit=${status} rows=${rows}/${EXPECTED_ROWS}"

        if [ "$status" -eq 0 ] && [ "$rows" -ge "$EXPECTED_ROWS" ]; then
            echo "  [$(date +%H:%M:%S)] ${slug} complete"
            return 0
        fi

        concurrency=$(( concurrency / 2 ))
        [ "$concurrency" -lt 4 ] && concurrency=4
        echo "  [$(date +%H:%M:%S)] ${slug} backing off to concurrency ${concurrency}"
        stop_my_servers
        sleep 60
    done

    echo "  [$(date +%H:%M:%S)] ${slug} INCOMPLETE after 3 attempts (${rows}/${EXPECTED_ROWS})"
    return 1
}

WANTED=("$@")
for entry in "${MODELS[@]}"; do
    IFS='|' read -r key slug base_url model token_var model_concurrency <<< "$entry"
    if [ ${#WANTED[@]} -gt 0 ] && [[ ! " ${WANTED[*]} " =~ " ${key} " ]]; then
        continue
    fi

    echo "==============================================================="
    echo "[$(date +%H:%M:%S)] MODEL ${key} (${model})"
    echo "==============================================================="

    write_env_yaml "$base_url" "$model" "$token_var"
    stop_my_servers
    run_model "$slug" "${CONCURRENCY_OVERRIDE:-$model_concurrency}"
done

stop_my_servers
echo "[$(date +%H:%M:%S)] All requested InjecAgent models finished."
