# Shared helpers for benchmark campaign runners (`*/run_all_models.sh`).
#
# WHY THIS EXISTS
#
# Several campaigns run side by side on one host, each out of its own worktree. A runner
# that cleans up with `pkill -9 -f "gym env start"` (or "gym eval run", or
# "responses_api_models/.*app.py") matches every *other* campaign's processes too, so each
# runner SIGKILLs its neighbours' server stacks mid-run. The victims report `Killed: 9` /
# exit=137 and "Head server finished unexpectedly", then halve their concurrency, which
# reads like OOM or endpoint throttling and is neither. Observed 2026-09-20 with three
# campaigns (xstest, kidbench, asb) running at once.
#
# Narrowing the pkill pattern to the worktree path does NOT work: runners invoke
# `.venv/bin/gym` relatively, so the absolute path never appears in argv, and a pattern
# that silently matches nothing is worse than no cleanup at all -- it leaves the previous
# runner alive and the two then tear down each other's servers.
#
# So each invocation pins its own head port and port block, writes them into a
# per-invocation env file, and only ever kills what listens on those ports.
#
# GOTCHA: A root `env.yaml` is auto-loaded by Gym and merged *after* everything passed
# with `--config`, so it silently overrides per-invocation port and model settings. That
# is why runners must write `env.<key>.yaml` rather than `env.yaml`, pass it explicitly
# with `--config`, and call `gym_runner_clear_shadowing_env_yaml` first.
#
# GOTCHA: `gym env status` takes no `--config`, so it always reports the *default* head
# port (11000) -- i.e. some other campaign's stack. Use `gym_runner_wait_for_head`, which
# polls this invocation's own head port.
#
# CONTRACT -- set these before calling anything here:
#   GYM_RUNNER_NAME   short campaign name, used in messages and the lock file
#   HEAD_PORT         this invocation's head server port
#   PORT_LOW          low end of this invocation's port block
#   PORT_HIGH         high end of this invocation's port block
#   ENV_YAML          per-invocation env file, relative to the repo root
#
# Port blocks in use on the FDR campaign host. Keep new campaigns disjoint from these and
# from Gym's default range, or the port-scoped cleanup below is back to killing neighbours:
#   (Gym default)  head 11000, ports 10001-20000  -- anything that does not pin
#   asb            head 11400, ports 20001-29000
#   kidbench       head 11500, ports 30001-34000
#   xstest         head 11600, ports 34001-38000
#   over_refusal   head 11700, ports 38001-42000

# Emit the port-pinning block for a generated env file. Callers paste this at the top of
# their own heredoc so the pinning travels with the config the run actually loads.
gym_runner_ports_yaml() {
    cat <<YAML
# Ports are pinned so this stack cannot collide with another campaign on this host.
head_server:
  port: ${HEAD_PORT}
port_range_low: ${PORT_LOW}
port_range_high: ${PORT_HIGH}
YAML
}

# Remove a generated root env.yaml, which would otherwise be auto-loaded last and shadow
# the per-invocation env file. A hand-written one is left alone unless it actually defines
# a shadowing key, in which case we stop rather than evaluate the wrong model or port.
gym_runner_clear_shadowing_env_yaml() {
    [ -f env.yaml ] || return 0
    if [ "$ENV_YAML" = "env.yaml" ]; then
        return 0  # the caller is using the dotenv itself; nothing to shadow
    fi
    if head -5 env.yaml | grep -q "Generated by .*run_all_models.sh"; then
        echo "  removing generated env.yaml (it would shadow ${ENV_YAML})"
        rm -f env.yaml
        return 0
    fi
    if grep -qE '^(head_server|port_range_low|port_range_high|policy_model):' env.yaml; then
        echo "ERROR: env.yaml is auto-loaded after --config and defines keys that would override" >&2
        echo "       ${ENV_YAML}. Move it aside before running this campaign." >&2
        return 1
    fi
    return 0
}

# Kill only this invocation's processes: whatever listens on its head port or inside its
# port block, plus any gym process started against its env file.
gym_runner_stop_servers() {
    local pid port
    for pid in $(pgrep -f "gym (env start|eval run).*${ENV_YAML}" 2>/dev/null); do
        kill -9 "$pid" 2>/dev/null
    done
    for pid in $(lsof -nP -iTCP:"${HEAD_PORT}" -sTCP:LISTEN -t 2>/dev/null); do
        kill -9 "$pid" 2>/dev/null
    done
    for port in $(lsof -nP -iTCP -sTCP:LISTEN 2>/dev/null | awk '{print $9}' | sed 's/.*://' \
                  | grep -E '^[0-9]+$' | sort -u); do
        if [ "$port" -ge "$PORT_LOW" ] && [ "$port" -le "$PORT_HIGH" ]; then
            for pid in $(lsof -nP -iTCP:"$port" -sTCP:LISTEN -t 2>/dev/null); do
                kill -9 "$pid" 2>/dev/null
            done
        fi
    done
    sleep 5
}

# Poll this invocation's own head port. $1 is the server log to watch for an early death.
gym_runner_wait_for_head() {
    local log="$1" i
    for i in $(seq 1 60); do
        sleep 5
        if [ -n "$log" ] && grep -q "Head server finished unexpectedly" "$log" 2>/dev/null; then
            echo "  ERROR: server stack died (see ${log})" >&2
            return 1
        fi
        if curl -s -m 2 "http://127.0.0.1:${HEAD_PORT}/" >/dev/null 2>&1; then
            sleep 20  # let the child servers finish binding
            echo "  servers up"
            return 0
        fi
    done
    echo "  ERROR: servers did not come up on head port ${HEAD_PORT}" >&2
    return 1
}

gym_runner_head_is_up() {
    curl -s -m 3 "http://127.0.0.1:${HEAD_PORT}/" >/dev/null 2>&1
}

# Refuse to start a second instance against the same ports: two runners sharing a port
# block fight over both the ports and the output files, and each one's cleanup kills the
# other's servers. $1 is a directory to keep the lock in (usually RESULTS_DIR).
gym_runner_lock() {
    local lock_dir="$1"
    local lock_file="${lock_dir}/.runner.${HEAD_PORT}.lock"
    if [ -f "$lock_file" ] && kill -0 "$(cat "$lock_file" 2>/dev/null)" 2>/dev/null; then
        echo "ERROR: a ${GYM_RUNNER_NAME} runner is already active on head port ${HEAD_PORT}" >&2
        echo "       (pid $(cat "$lock_file")). Stop it first, or pass a different" >&2
        echo "       HEAD_PORT/PORT_LOW/PORT_HIGH/ENV_YAML." >&2
        return 1
    fi
    echo $$ > "$lock_file"
    # shellcheck disable=SC2064  # expand lock_file now, not at trap time
    trap "rm -f '$lock_file'" EXIT
    return 0
}
